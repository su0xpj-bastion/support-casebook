"""Write docs/test-matrix.md: one row per pack, with the tests that cover it.

Coverage comes from pytest's own collection (no tests are run): a test covers a pack when its
node id carries the pack id as a parameter ("[AN-01]") or in its name ("test_an01_...").
Regenerate after adding packs or tests:

    python tools/gen_test_matrix.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from casebook import packs  # noqa: E402

OUT = ROOT / "docs" / "test-matrix.md"
# Tests that check a pack's files, not its behaviour. Every pack has these, so they don't count as coverage.
METADATA_ONLY = {"test_pack_metadata_complete", "test_pack_provenance_tagged_per_field", "test_every_identity_pack_is_labelled"}


def collected() -> list[str]:
    r = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q"], cwd=ROOT,
                       capture_output=True, text=True, check=True)
    return [line for line in r.stdout.splitlines() if "::" in line]


def coverage(node_ids: list[str], pack_ids: list[str]) -> dict[str, list[str]]:
    by_pack: dict[str, set[str]] = defaultdict(set)
    for nid in node_ids:
        path, _, name = nid.partition("::")
        base = name.split("[")[0]
        param = name[len(base):]
        for pid in pack_ids:
            short = pid.replace("-", "").lower()
            if f"[{pid}]" in param or re.search(rf"_{short}(_|$)", base) or param.startswith(f"[{pid}-"):
                by_pack[pid].add(f"`{Path(path).name}::{base}`")
    return {pid: sorted(v) for pid, v in by_pack.items()}


def render(all_packs: dict[str, packs.Pack], cov: dict[str, list[str]], total: int) -> str:
    lines = [
        "# Test matrix",
        "",
        "Generated by `tools/gen_test_matrix.py` from the pack files and pytest's collection. Do not edit by hand.",
        "",
        f"{len(all_packs)} packs, {total} collected test cases. "
        "This file lists which tests exist for each pack. It does not record whether they passed; "
        "CI does (`.github/workflows/ci.yml`).",
        "",
        "| Pack | Title | Kind | Surface | Retry | Expected verdict | Provenance | Tests |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for pid in sorted(all_packs, key=lambda x: (x.split("-")[0], int(x.split("-")[1]))):
        p = all_packs[pid]
        m = p.meta
        verdict = (m.get("verdict") or {}).get("cls", "-")
        tests = "<br>".join(cov.get(pid, [])) or "**none**"
        title = str(m.get("title", "")).replace("|", "\\|")
        lines.append(f"| {pid} | {title} | {m.get('kind', 'error')} | {m.get('surface', '-')} | "
                     f"{m.get('retry', '-')} | `{verdict}` | {p.provenance} | {tests} |")
    uncovered = _behaviour_gaps(all_packs, cov)
    lines += ["", "Every pack also has the two file checks (`test_pack_metadata_complete`, "
              "`test_pack_provenance_tagged_per_field`), which don't test behaviour.",
              "", f"Packs with no behavioural test: {', '.join(uncovered) or 'none'}.", ""]
    return "\n".join(lines)


def _behaviour_gaps(all_packs: dict[str, packs.Pack], cov: dict[str, list[str]]) -> list[str]:
    def behavioural(tests: list[str]) -> bool:
        return any(t.strip("`").split("::")[1] not in METADATA_ONLY for t in tests)
    return sorted(pid for pid in all_packs if not behavioural(cov.get(pid, [])))


def main() -> int:
    all_packs = packs.load_all()
    nodes = collected()
    cov = coverage(nodes, list(all_packs))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(all_packs, cov, len(nodes)), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(all_packs)} packs, {len(nodes)} tests, "
          f"{len(_behaviour_gaps(all_packs, cov))} packs without a behavioural test")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
